def filter_data(WK):
    if len(WK)<=15:
        return [0]*len(WK)
    N = 4  # Filter order
    Wn = 0.1  # Cutoff frequency
    B, A = butter(N, Wn, output='ba')
    smooth_data = filtfilt(B, A, WK)
    return smooth_data


def plot(in1, in2):
    plt.subplot(1, 2, 1)
    plt.title("滤波前", fontsize=8)
    plt.plot(in1, c="y", label="CURRENT")
    plt.title("滤波后", fontsize=8)
    plt.plot(in2, c="b", label="CURRENT")
    plt.show()


